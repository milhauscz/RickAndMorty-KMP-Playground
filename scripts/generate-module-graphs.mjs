#!/usr/bin/env node
/**
 * Generate module-graph *.mmd files from module-deps.json.
 * Straight arrows (ELK + linear), direct edges — no merge buses.
 *
 * Edit docs/images/module-deps.json, then run scripts/render-module-graphs.ps1
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const imagesDir = join(__dirname, "..", "docs", "images");
const spec = JSON.parse(readFileSync(join(imagesDir, "module-deps.json"), "utf8"));

const INIT = `%%{init: {"flowchart": {"defaultRenderer": "elk", "htmlLabels": true, "curve": "linear"}}}%%`;

/** @param {unknown[]} raw */
function parseEdge(raw) {
  const [from, to, opts = {}] = raw;
  return { from, to, dashed: opts.style === "dashed" };
}

const allEdges = spec.edges.map(parseEdge);

/** @param {{ from: string, to: string, dashed?: boolean }} edge */
function mermaidEdge(edge) {
  const link = edge.dashed ? "-.->" : "-->";
  return `    ${edge.from} ${link} ${edge.to}`;
}

/** @param {Set<string>} nodeIds */
function edgesFor(nodeIds) {
  return allEdges.filter((e) => nodeIds.has(e.from) && nodeIds.has(e.to));
}

function writeMmd(basename, lines) {
  writeFileSync(join(imagesDir, `${basename}.mmd`), lines.join("\n") + "\n");
  console.log(`Generated ${basename}.mmd`);
}

// --- Overview ---
{
  const nodeIds = new Set(spec.overviewNodes);
  const lines = [
    INIT,
    "flowchart TB",
    "    %% Apps, shared, runtime, and feature modules only (no :core:*).",
    "    %% iosApp is an Xcode target (not a Gradle module) that links the :shared framework.",
    "    %% Arrow direction: consumer --> dependency.",
    "",
    ...spec.overviewNodes.map((id) => `    ${id}["${spec.nodes[id].label}"]`),
    "",
    ...edgesFor(nodeIds).map(mermaidEdge),
  ];
  writeMmd("module-graph-overview", lines);
}

// --- Full ---
{
  const lines = [
    INIT,
    "flowchart TB",
    "    %% Full direct Gradle dependencies. Arrow direction: consumer --> dependency.",
    "",
    '    subgraph apps ["Apps"]',
    "        direction LR",
    '        androidApp[":androidApp"]',
    '        iosApp[":iosApp"]',
    "    end",
    "",
    '    subgraph umbrella ["Demo / SDK"]',
    "        direction LR",
    '        shared[":shared"]',
    '        runtime[":runtime"]',
    "    end",
    "",
    '    subgraph characters ["Characters"]',
    "        direction LR",
    '        charsUi[":feature:characters:ui"]',
    '        charsImpl[":feature:characters:impl"]',
    '        charsApi[":feature:characters:api"]',
    "    end",
    "",
    '    subgraph episode ["Episode"]',
    "        direction LR",
    '        epImpl[":feature:episode:impl"]',
    '        epApi[":feature:episode:api"]',
    "    end",
    "",
    '    subgraph location ["Location"]',
    "        direction LR",
    '        locImpl[":feature:location:impl"]',
    '        locApi[":feature:location:api"]',
    "    end",
    "",
    '    subgraph core ["Core"]',
    "        direction LR",
    '        common[":core:common"]',
    '        network[":core:network"]',
    '        database[":core:database"]',
    '        designsystem[":core:designsystem"]',
    '        featureflags[":core:featureflags"]',
    '        image[":core:image"]',
    "    end",
    "",
    ...allEdges.map(mermaidEdge),
  ];
  writeMmd("module-graph", lines);
}

// --- Per core module ---
for (const target of spec.coreTargets) {
  const nodeIds = new Set([target]);
  const edges = [];
  for (const edge of allEdges) {
    if (edge.to === target) {
      nodeIds.add(edge.from);
      edges.push(edge);
    }
  }
  const targetLabel = spec.nodes[target].label;
  const lines = [
    INIT,
    "flowchart LR",
    `    %% Direct dependents of ${targetLabel}`,
    "",
    `    ${target}["${targetLabel}"]`,
    ...edges.map((edge) => {
      const fromLabel = spec.nodes[edge.from].label;
      if (edge.from === target) return null;
      const link = edge.dashed ? "-.->" : "-->";
      return `    ${edge.from}["${fromLabel}"] ${link} ${target}`;
    }).filter(Boolean),
  ];
  writeMmd(`module-graph-core-${target}`, lines);
}

// --- Markdown table ---
const tableLines = [
  "# Module dependencies",
  "",
  "Direct Gradle `implementation` / `api` project dependencies.",
  "Regenerated by `scripts/render-module-graphs.ps1`.",
  "",
  "| Consumer | Depends on |",
  "| --- | --- |",
];
for (const [from, to] of spec.edges.map((e) => [e[0], e[1]])) {
  const fromLabel = spec.nodes[from]?.label ?? from;
  const toLabel = spec.nodes[to]?.label ?? to;
  tableLines.push(`| \`${fromLabel}\` | \`${toLabel}\` |`);
}
tableLines.push("");
writeFileSync(join(imagesDir, "module-deps.md"), tableLines.join("\n"));
console.log("Generated module-deps.md");

console.log("Done.");
